/**
 * Draw the module map from the imports, not from memory.
 *
 * An architecture note written by hand is right on the day it is written. This
 * one is read out of the import graph, so it is right or the check fails.
 *
 * The interesting output is not the list of layers, it is the list of edges
 * that should not exist. The rule this build holds to is that layers only
 * depend downwards: core knows nothing, the store knows core, the domain knows
 * both, and the command line and the read service know everything and are
 * known by nothing. An edge the wrong way is how a domain module ends up
 * unable to be used without a command line around it.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Layers, outermost last. A layer may import from any layer before it. */
const LAYERS = [
  { name: 'core', dirs: ['core'] },
  { name: 'store', dirs: ['store'] },
  {
    name: 'domain',
    dirs: [
      'property',
      'booking',
      'catalog',
      'covers',
      'production',
      'labour',
      'billing',
      'orders',
      'timeline',
      'equipment',
      'bar',
    ],
  },
  { name: 'reporting', dirs: ['reports', 'audit', 'demo'] },
  { name: 'workflow', dirs: ['workflow'] },
  { name: 'edges', dirs: ['cli', 'http'] },
];

const LAYER_OF = new Map();
for (const [index, layer] of LAYERS.entries()) {
  for (const dir of layer.dirs) {
    LAYER_OF.set(dir, { name: layer.name, index });
  }
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) {
      out.push(...walk(path));
    } else if (name.endsWith('.ts')) {
      out.push(path.split('\\').join('/'));
    }
  }
  return out;
}

function areaOf(file) {
  return file.split('/')[1] ?? '';
}

const files = walk('src');
const edges = new Map();
const problems = [];

for (const file of files) {
  const from = areaOf(file);
  const fromLayer = LAYER_OF.get(from);
  if (fromLayer === undefined) {
    continue;
  }
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(/from '(\.\.?\/[^']+)'/g)) {
    const target = match[1];
    // '../billing/charges.js' names its area in the first segment after the
    // dots; a same-folder import names none and is not an edge.
    const parts = target.split('/').filter((part) => part !== '..' && part !== '.');
    if (parts.length < 2) {
      continue;
    }
    const to = parts[0];
    const toLayer = LAYER_OF.get(to);
    if (toLayer === undefined || to === from) {
      continue;
    }
    const key = `${from} -> ${to}`;
    edges.set(key, (edges.get(key) ?? 0) + 1);
    if (toLayer.index > fromLayer.index) {
      problems.push(`${file} imports ${to}: ${fromLayer.name} must not depend on ${toLayer.name}`);
    }
  }
}

const lines = [];
lines.push('# The module map');
lines.push('');
lines.push('Generated by `scripts/generate-map.mjs`. Do not edit by hand.');
lines.push('');
lines.push('Layers depend downwards only. A layer may import anything above it in this list.');
lines.push('');
for (const layer of LAYERS) {
  lines.push(`- **${layer.name}** — ${layer.dirs.map((dir) => `\`${dir}\``).join(', ')}`);
}
lines.push('');
lines.push('## What imports what');
lines.push('');
lines.push('| from | to | imports |');
lines.push('| --- | --- | --- |');
for (const [key, count] of [...edges.entries()].sort()) {
  const [from, to] = key.split(' -> ');
  lines.push(`| \`${from}\` | \`${to}\` | ${count} |`);
}
lines.push('');
lines.push(`${files.length} source files, ${edges.size} edges between areas.`);
lines.push('');

const rendered = `${lines.join('\n')}`;
const target = 'docs/architecture.md';
const checking = process.argv.includes('--check');

if (problems.length > 0) {
  console.error(`${problems.length} edge(s) point the wrong way:`);
  for (const problem of problems.sort()) {
    console.error(`  ${problem}`);
  }
  process.exit(1);
}

if (checking) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    current = '';
  }
  if (current !== rendered) {
    console.error(`${target} is out of date, run npm run map`);
    process.exit(1);
  }
  console.log(`${target} is current, ${edges.size} edges all pointing downwards`);
} else {
  writeFileSync(target, rendered);
  console.log(`${target} written, ${edges.size} edges all pointing downwards`);
}
